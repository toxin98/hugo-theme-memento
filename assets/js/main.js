document.addEventListener("DOMContentLoaded", () => {
  document.querySelectorAll(".highlight").forEach(block => {
    const code = block.querySelector("code");

    if (!code) return;

    const button = document.createElement("button");

    button.className = "code-copy";
    button.textContent = "Copy";

    button.addEventListener("click", async () => {
      await navigator.clipboard.writeText(code.textContent);

      button.textContent = "Copied";

      setTimeout(() => {
        button.textContent = "Copy";
      }, 1500);
    });

    block.appendChild(button);
  });
});

document.addEventListener("DOMContentLoaded", () => {
  function updateLocalTime(el) {
    const date = new Date(el.dateTime);
    const layout = el.dataset.timeLayout;

    if (Number.isNaN(date.getTime())) {
      return;
    }

    // 辅助函数：补齐双位数 (例如 8 -> "08")
    const pad = num => String(num).padStart(2, '0');

    const year = date.getFullYear();
    const month = pad(date.getMonth() + 1);
    const day = pad(date.getDate());
    const hours = pad(date.getHours());
    const minutes = pad(date.getMinutes());
    const seconds = pad(date.getSeconds());

    let output = "";

    switch (layout) {
      case "notes":
        output = `${year}/${month}/${day} ${hours}:${minutes}`;
        break;

      case "posts":
        output = `${year}/${month}/${day}`;
        break;

      case "ephemera": {
        // 独立获取星期英文全称
        const weekday = new Intl.DateTimeFormat("en-US", { weekday: "long" }).format(date);
        output = `${year}/${month}/${day} ${hours}:${minutes} ${weekday}`;
        break;
      }

      default:
        return;
    }

    el.textContent = output;
    el.hidden = false;
  }

  document.querySelectorAll(".local-time").forEach(updateLocalTime)

  const observer = new MutationObserver(mutations => {
    console.log("[local-time] DOM mutation", mutations);
    mutations.forEach(mutation => {
      mutation.addedNodes.forEach(node => {
        if (node.nodeType !== Node.ELEMENT_NODE) {
          return;
        }

        if (node.matches(".local-time")) {
          updateLocalTime(node);
        }

        node.querySelectorAll(".local-time")
          .forEach(updateLocalTime);
      });
    });
  });

  observer.observe(document.body, {
    childList: true,
    subtree: true
  });
});

document.addEventListener("DOMContentLoaded", () => {
  const asideToggleBtn = document.querySelector(".notes-aside-toggle");
  const asideContainer = document.querySelector(".notes-reading-aside");

  if (asideToggleBtn && asideContainer) {
    // 1. 点击按钮呼出/收起卡片[cite: 1]
    asideToggleBtn.addEventListener("click", (e) => {
      e.stopPropagation(); // 阻止事件冒泡[cite: 1]
      asideContainer.classList.toggle("open");
    });

    // 2. 点击空白处关闭侧边栏[cite: 1]
    document.addEventListener("click", (e) => {
      // 仅在窄屏且目录显示时处理[cite: 1]
      if (window.innerWidth <= 768 && asideContainer.classList.contains("open")) {
        // 如果点击的目标不是 aside 容器内部，也不是触发按钮本身，则关闭[cite: 1]
        if (!asideContainer.contains(e.target) && !asideToggleBtn.contains(e.target)) {
          asideContainer.classList.remove("open");
        }
      }
    });

    // 3. 点击 TOC 里的链接后自动收起目录（优化手机端阅读体验）[cite: 1]
    const tocLinks = asideContainer.querySelectorAll(".toc-container a");
    tocLinks.forEach(link => {
      link.addEventListener("click", () => {
        if (window.innerWidth <= 768) {
          asideContainer.classList.remove("active");
        }
      });
    });
  }
});

